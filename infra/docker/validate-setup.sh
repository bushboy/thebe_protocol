#!/bin/bash
# Validation script for Docker deployment setup
# This script checks that all prerequisites are in place before running docker-compose

set -e

echo "=== Zero-Trust Agentic Guardian - Docker Setup Validation ==="
echo ""

# Color codes for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# Track validation status
ERRORS=0
WARNINGS=0

# Function to print error
error() {
    echo -e "${RED}[ERROR]${NC} $1"
    ERRORS=$((ERRORS + 1))
}

# Function to print warning
warning() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
    WARNINGS=$((WARNINGS + 1))
}

# Function to print success
success() {
    echo -e "${GREEN}[OK]${NC} $1"
}

echo "1. Checking Docker installation..."
if command -v docker &> /dev/null; then
    DOCKER_VERSION=$(docker --version)
    success "Docker is installed: $DOCKER_VERSION"
else
    error "Docker is not installed. Please install Docker first."
fi

echo ""
echo "2. Checking Docker Compose installation..."
if command -v docker-compose &> /dev/null; then
    COMPOSE_VERSION=$(docker-compose --version)
    success "Docker Compose is installed: $COMPOSE_VERSION"
else
    error "Docker Compose is not installed. Please install Docker Compose first."
fi

echo ""
echo "3. Checking environment file..."
if [ -f ".env" ]; then
    success "Environment file (.env) exists"
    
    # Check for required variables
    REQUIRED_VARS=(
        "AUTH0_DOMAIN"
        "AUTH0_AUDIENCE"
        "INTENT_ENGINE_CLIENT_ID"
        "PLANNER_CLIENT_ID"
        "SAFETY_AGENT_CLIENT_ID"
        "PERMISSION_BROKER_CLIENT_ID"
        "EXECUTOR_CLIENT_ID"
        "AUDIT_CLIENT_ID"
        "POSTGRES_PASSWORD"
        "REDIS_PASSWORD"
    )
    
    for VAR in "${REQUIRED_VARS[@]}"; do
        if grep -q "^${VAR}=" .env && ! grep -q "^${VAR}=your-" .env && ! grep -q "^${VAR}=$" .env; then
            success "  $VAR is set"
        else
            error "  $VAR is not set or uses placeholder value"
        fi
    done
else
    error "Environment file (.env) not found. Copy .env.example to .env and configure it."
fi

echo ""
echo "4. Checking certificate directory..."
if [ -d "../certificates/root-ca" ]; then
    success "Root CA directory exists"
    
    if [ -f "../certificates/root-ca/ca.crt" ]; then
        success "  Root CA certificate found"
    else
        error "  Root CA certificate not found. Run infra/certificates/generate_all_certs.sh"
    fi
else
    error "Certificate directory not found. Run infra/certificates/generate_all_certs.sh"
fi

# Check service certificates
SERVICES=("intent-engine" "planner" "safety-agent" "permission-broker" "executor" "audit")
echo ""
echo "5. Checking service certificates..."
for SERVICE in "${SERVICES[@]}"; do
    if [ -d "../certificates/${SERVICE}" ]; then
        if [ -f "../certificates/${SERVICE}/client.crt" ] && \
           [ -f "../certificates/${SERVICE}/client.key" ] && \
           [ -f "../certificates/${SERVICE}/server.crt" ] && \
           [ -f "../certificates/${SERVICE}/server.key" ]; then
            success "  ${SERVICE} certificates complete"
        else
            error "  ${SERVICE} certificates incomplete"
        fi
    else
        error "  ${SERVICE} certificate directory not found"
    fi
done

echo ""
echo "6. Checking OPA policies..."
if [ -d "../opa/policies" ]; then
    POLICY_COUNT=$(find ../opa/policies -name "*.rego" | wc -l)
    if [ "$POLICY_COUNT" -gt 0 ]; then
        success "Found $POLICY_COUNT OPA policy files"
    else
        warning "No .rego policy files found in ../opa/policies"
    fi
else
    error "OPA policies directory not found"
fi

echo ""
echo "7. Checking DPoP keys directory..."
if [ -d "../../keys" ]; then
    success "Keys directory exists"
    
    # Check for DPoP keys
    for SERVICE in "${SERVICES[@]}"; do
        if [ -f "../../keys/${SERVICE}-dpop.pem" ]; then
            success "  ${SERVICE} DPoP key found"
        else
            warning "  ${SERVICE} DPoP key not found (will be generated by Auth0 setup)"
        fi
    done
else
    warning "Keys directory not found. Will be created by Auth0 setup script."
fi

echo ""
echo "8. Checking Docker daemon..."
if docker info &> /dev/null; then
    success "Docker daemon is running"
else
    error "Docker daemon is not running. Please start Docker."
fi

echo ""
echo "=== Validation Summary ==="
if [ $ERRORS -eq 0 ] && [ $WARNINGS -eq 0 ]; then
    echo -e "${GREEN}All checks passed! You can run 'docker-compose up -d'${NC}"
    exit 0
elif [ $ERRORS -eq 0 ]; then
    echo -e "${YELLOW}Validation completed with $WARNINGS warning(s).${NC}"
    echo "You can proceed, but some features may not work correctly."
    exit 0
else
    echo -e "${RED}Validation failed with $ERRORS error(s) and $WARNINGS warning(s).${NC}"
    echo "Please fix the errors before running docker-compose."
    exit 1
fi
